package org.allbinary.gdevelop.loader.comparison;

import java.io.BufferedWriter;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.TreeSet;

/**
 * Compares language files generated directly from the language xsl (for example Kt.xsl) by GDLanguageGenerationHarness
 * with the files in the language modules (for example *KtM) generated by converting the generated Java.
 * Formatting and comments are ignored. Each file is normalized to one statement per line and written to
 * outputPath\gen and outputPath\ref so differences can be viewed with: git diff --no-index outputPath\ref outputPath\gen
 *
 * Usage: GDLanguageOutputComparison genPath referencePath outputPath [extension=.kt] [-loose]
 * -loose also ignores !!, val/var, @Throws, protected before override, : Object, empty : super() and empty public constructor differences.
 * Modifier order is always ignored.
 */
public class GDLanguageOutputComparison {

    private static final String[] OPERATOR_ARRAY = {
        "..<", "===", "!==", "!!", "?.", "?:", "::", "->", "==", "!=", "<=", ">=", "&&", "||", "++", "--",
        "+=", "-=", "*=", "/=", "%=", "..",
    };

    private static final String NEWLINE = "\n";

    private final boolean loose;

    public GDLanguageOutputComparison(final boolean loose) {
        this.loose = loose;
    }

    public static void main(final String[] args) throws Exception {
        if (args.length < 3) {
            System.out.println("Usage: GDLanguageOutputComparison genPath referencePath outputPath [extension=.kt] [-loose]");
            System.exit(1);
        }
        String extension = ".kt";
        boolean loose = false;
        for (int index = 3; index < args.length; index++) {
            if (args[index].equals("-loose")) {
                loose = true;
            } else {
                extension = args[index];
            }
        }
        final int result = new GDLanguageOutputComparison(loose).process(new File(args[0]), new File(args[1]), new File(args[2]), extension);
        System.exit(result);
    }

    public int process(final File genRoot, final File refRoot, final File outputRoot, final String extension) throws Exception {
        final List<File> genFileList = new ArrayList<File>();
        this.collect(genRoot, extension, genFileList);
        Collections.sort(genFileList);

        final File genOutputRoot = new File(outputRoot, "gen");
        final File refOutputRoot = new File(outputRoot, "ref");

        final StringBuilder report = new StringBuilder();
        int same = 0;
        int different = 0;
        int missing = 0;
        final String genRootPath = genRoot.getCanonicalPath();
        for (final File genFile : genFileList) {
            final String relativePath = genFile.getCanonicalPath().substring(genRootPath.length() + 1);
            final File refFile = new File(refRoot, relativePath);
            if (!refFile.exists()) {
                missing++;
                report.append("MISSING_REFERENCE ").append(relativePath).append(NEWLINE);
                continue;
            }

            final Normalized gen = this.normalize(this.read(genFile));
            final Normalized ref = this.normalize(this.read(refFile));

            final TreeSet<String> missingImportSet = new TreeSet<String>(ref.importSet);
            missingImportSet.removeAll(gen.importSet);
            final TreeSet<String> extraImportSet = new TreeSet<String>(gen.importSet);
            extraImportSet.removeAll(ref.importSet);

            final boolean codeSame = gen.code.equals(ref.code);
            if (codeSame && missingImportSet.isEmpty()) {
                same++;
            } else {
                different++;
                report.append(codeSame ? "IMPORTS_ONLY " : "DIFFERENT ").append(relativePath).append(NEWLINE);
                for (final String importString : missingImportSet) {
                    report.append("    missing import ").append(importString).append(NEWLINE);
                }
                for (final String importString : extraImportSet) {
                    report.append("    extra import ").append(importString).append(NEWLINE);
                }
            }
            this.write(new File(genOutputRoot, relativePath), gen.toString());
            this.write(new File(refOutputRoot, relativePath), ref.toString());
        }

        report.append("same=").append(same).append(" different=").append(different).append(" missingReference=").append(missing).append(NEWLINE);
        this.write(new File(outputRoot, "report.txt"), report.toString());
        System.out.print(report.toString());
        return different > 0 ? 2 : 0;
    }

    private void collect(final File directory, final String extension, final List<File> fileList) {
        final File[] fileArray = directory.listFiles();
        if (fileArray == null) {
            return;
        }
        for (final File file : fileArray) {
            if (file.isDirectory()) {
                this.collect(file, extension, fileList);
            } else if (file.getName().endsWith(extension)) {
                fileList.add(file);
            }
        }
    }

    private String read(final File file) throws IOException {
        final FileInputStream inputStream = new FileInputStream(file);
        try {
            final byte[] byteArray = new byte[(int) file.length()];
            int offset = 0;
            while (offset < byteArray.length) {
                final int read = inputStream.read(byteArray, offset, byteArray.length - offset);
                if (read < 0) {
                    break;
                }
                offset += read;
            }
            return new String(byteArray, 0, offset, "UTF-8");
        } finally {
            inputStream.close();
        }
    }

    private void write(final File file, final String text) throws IOException {
        file.getParentFile().mkdirs();
        final BufferedWriter writer = new BufferedWriter(new OutputStreamWriter(new FileOutputStream(file), "UTF-8"));
        try {
            writer.write(text);
        } finally {
            writer.close();
        }
    }

    private static class Normalized {
        final TreeSet<String> importSet = new TreeSet<String>();
        String code;

        public String toString() {
            final StringBuilder stringBuilder = new StringBuilder();
            for (final String importString : this.importSet) {
                stringBuilder.append("import ").append(importString).append(NEWLINE);
            }
            stringBuilder.append(this.code);
            return stringBuilder.toString();
        }
    }

    /**
     * Tokens with a NEWLINE token for each line break in the source. Comments are removed.
     */
    private List<String> tokenize(final String text) {
        final List<String> tokenList = new ArrayList<String>();
        final int length = text.length();
        int index = 0;
        while (index < length) {
            final char c = text.charAt(index);
            if (c == '\n') {
                tokenList.add(NEWLINE);
                index++;
            } else if (Character.isWhitespace(c)) {
                index++;
            } else if (text.startsWith("//", index)) {
                while (index < length && text.charAt(index) != '\n') {
                    index++;
                }
            } else if (text.startsWith("/*", index)) {
                int depth = 0;
                while (index < length) {
                    if (text.startsWith("/*", index)) {
                        depth++;
                        index += 2;
                    } else if (text.startsWith("*/", index)) {
                        depth--;
                        index += 2;
                        if (depth == 0) {
                            break;
                        }
                    } else {
                        index++;
                    }
                }
            } else if (text.startsWith("\"\"\"", index)) {
                final int end = text.indexOf("\"\"\"", index + 3);
                final int endIndex = end < 0 ? length : end + 3;
                tokenList.add(text.substring(index, endIndex));
                index = endIndex;
            } else if (c == '"' || c == '\'') {
                int end = index + 1;
                while (end < length && text.charAt(end) != c) {
                    if (text.charAt(end) == '\\') {
                        end++;
                    }
                    end++;
                }
                end = Math.min(end + 1, length);
                tokenList.add(text.substring(index, end));
                index = end;
            } else if (Character.isJavaIdentifierStart(c) || c == '`') {
                int end = index + 1;
                while (end < length && Character.isJavaIdentifierPart(text.charAt(end))) {
                    end++;
                }
                tokenList.add(text.substring(index, end));
                index = end;
            } else if (Character.isDigit(c)) {
                int end = index + 1;
                while (end < length && (Character.isLetterOrDigit(text.charAt(end)) || text.charAt(end) == '_'
                    || (text.charAt(end) == '.' && end + 1 < length && Character.isDigit(text.charAt(end + 1))))) {
                    end++;
                }
                tokenList.add(text.substring(index, end));
                index = end;
            } else {
                String operator = String.valueOf(c);
                for (final String multiCharacterOperator : OPERATOR_ARRAY) {
                    if (text.startsWith(multiCharacterOperator, index)) {
                        operator = multiCharacterOperator;
                        break;
                    }
                }
                tokenList.add(operator);
                index += operator.length();
            }
        }
        return tokenList;
    }

    private boolean isContinuationEnd(final String token) {
        return token.equals("(") || token.equals(",") || token.equals("=") || token.equals(".") || token.equals("?.")
            || token.equals("+") || token.equals("-") || token.equals("*") || token.equals("/") || token.equals("&&")
            || token.equals("||") || token.equals(":") || token.equals("->") || token.equals("?:") || token.equals("[")
            || token.equals("<") || token.equals("==") || token.equals("!=") || token.equals("!") || token.equals("override")
            || token.equals("open") || token.equals("private") || token.equals("protected") || token.equals("internal")
            || token.equals("abstract") || token.equals("final") || token.startsWith("@") || token.equals("else");
    }

    private boolean isContinuationStart(final String token) {
        return token.equals(")") || token.equals(".") || token.equals("?.") || token.equals(":") || token.equals("{")
            || token.equals(",") || token.equals("]") || token.equals("?:") || token.equals("&&") || token.equals("||")
            || token.equals("else") || token.equals("catch") || token.equals("finally") || token.equals("!!")
            || token.equals("+") || token.equals("*") || token.equals("/") || token.equals("as") || token.equals("is")
            || token.equals("=") || token.equals("(") || token.equals("->");
    }

    private Normalized normalize(final String text) {
        final List<String> tokenList = this.tokenize(text);
        final Normalized normalized = new Normalized();

        //Remove imports and join annotations to the next token
        final List<String> codeTokenList = new ArrayList<String>();
        final int size = tokenList.size();
        for (int index = 0; index < size; index++) {
            final String token = tokenList.get(index);
            if (token.equals("import") && (codeTokenList.isEmpty() || codeTokenList.get(codeTokenList.size() - 1).equals(NEWLINE))) {
                final StringBuilder stringBuilder = new StringBuilder();
                index++;
                while (index < size && !tokenList.get(index).equals(NEWLINE) && !tokenList.get(index).equals(";")) {
                    final String part = tokenList.get(index);
                    if (part.equals("as")) {
                        stringBuilder.append(' ').append(part).append(' ');
                    } else {
                        stringBuilder.append(part);
                    }
                    index++;
                }
                final String importString = stringBuilder.toString();
                if (!this.isIgnoredImport(importString)) {
                    normalized.importSet.add(importString);
                }
                continue;
            }
            if (token.equals("@") && index + 1 < size) {
                final StringBuilder stringBuilder = new StringBuilder("@");
                index++;
                stringBuilder.append(tokenList.get(index));
                if (index + 1 < size && tokenList.get(index + 1).equals("(")) {
                    int depth = 0;
                    while (index + 1 < size) {
                        index++;
                        final String part = tokenList.get(index);
                        if (part.equals(NEWLINE)) {
                            continue;
                        }
                        stringBuilder.append(part);
                        if (part.equals("(")) {
                            depth++;
                        } else if (part.equals(")")) {
                            depth--;
                            if (depth == 0) {
                                break;
                            }
                        }
                    }
                }
                final String annotation = stringBuilder.toString();
                if (this.loose && annotation.startsWith("@Throws")) {
                    continue;
                }
                codeTokenList.add(annotation);
                continue;
            }
            if (token.equals("public")) {
                continue;
            }
            if (this.loose) {
                if (token.equals("!!")) {
                    continue;
                }
                if (token.equals("protected") && index + 1 < size && tokenList.get(index + 1).equals("override")) {
                    continue;
                }
                if (token.equals("val")) {
                    codeTokenList.add("var");
                    continue;
                }
            }
            codeTokenList.add(token);
        }

        if (this.loose) {
            this.removeNeutralConverterIdioms(codeTokenList);
        }

        //One statement per line
        final StringBuilder stringBuilder = new StringBuilder();
        final List<String> lineTokenList = new ArrayList<String>();
        String previous = NEWLINE;
        final int size2 = codeTokenList.size();
        for (int index = 0; index < size2; index++) {
            final String token = codeTokenList.get(index);
            if (token.equals(NEWLINE) || token.equals(";")) {
                String next = NEWLINE;
                for (int index2 = index + 1; index2 < size2; index2++) {
                    if (!codeTokenList.get(index2).equals(NEWLINE)) {
                        next = codeTokenList.get(index2);
                        break;
                    }
                }
                if (token.equals(";") || (!this.isContinuationEnd(previous) && !this.isContinuationStart(next))) {
                    this.endLine(stringBuilder, lineTokenList);
                }
                continue;
            }
            if (token.equals("}")) {
                this.endLine(stringBuilder, lineTokenList);
                lineTokenList.add(token);
                String next = NEWLINE;
                for (int index2 = index + 1; index2 < size2; index2++) {
                    if (!codeTokenList.get(index2).equals(NEWLINE)) {
                        next = codeTokenList.get(index2);
                        break;
                    }
                }
                if (!next.equals("else") && !next.equals("catch") && !next.equals("finally") && !next.equals(")") && !next.equals(",") && !next.equals(".")) {
                    this.endLine(stringBuilder, lineTokenList);
                }
            } else if (token.equals("{")) {
                lineTokenList.add(token);
                this.endLine(stringBuilder, lineTokenList);
            } else {
                lineTokenList.add(token);
            }
            previous = token;
        }
        this.endLine(stringBuilder, lineTokenList);
        normalized.code = stringBuilder.toString();
        return normalized;
    }

    private static final String[] OBJECT_SUPER_TYPE = {":", "Object", "{"};
    private static final String[] EMPTY_SUPER_CALL = {":", "super", "(", ")", "{"};
    private static final String[] EMPTY_CONSTRUCTOR = {"constructor", "(", ")", "{", "}"};

    /**
     * Returns the index after the pattern when it matches at index ignoring NEWLINE tokens otherwise -1.
     */
    private int match(final List<String> tokenList, final int start, final String[] pattern) {
        int index = start;
        final int size = tokenList.size();
        for (final String part : pattern) {
            while (index < size && tokenList.get(index).equals(NEWLINE)) {
                index++;
            }
            if (index >= size || !tokenList.get(index).equals(part)) {
                return -1;
            }
            index++;
        }
        return index;
    }

    private String previousToken(final List<String> tokenList, final int start) {
        for (int index = start - 1; index >= 0; index--) {
            if (!tokenList.get(index).equals(NEWLINE)) {
                return tokenList.get(index);
            }
        }
        return NEWLINE;
    }

    /**
     * The converter extends Object, delegates to an empty super() and adds empty public constructors which are the Kotlin defaults.
     */
    private void removeNeutralConverterIdioms(final List<String> tokenList) {
        for (int index = 0; index < tokenList.size(); index++) {
            int end = this.match(tokenList, index, OBJECT_SUPER_TYPE);
            if (end < 0) {
                end = this.match(tokenList, index, EMPTY_SUPER_CALL);
            }
            if (end >= 0) {
                tokenList.subList(index, end - 1).clear();
                continue;
            }
            end = this.match(tokenList, index, EMPTY_CONSTRUCTOR);
            if (end >= 0) {
                final String previous = this.previousToken(tokenList, index);
                if (!previous.equals("private") && !previous.equals("protected") && !previous.equals("internal")) {
                    tokenList.subList(index, end).clear();
                    index--;
                }
            }
        }
    }

    private static final String[] MODIFIER_ARRAY = {
        "open", "override", "private", "protected", "internal", "abstract", "final", "const", "lateinit", "inline", "data", "inner", "companion",
    };

    private boolean isModifier(final String token) {
        if (token.startsWith("@")) {
            return true;
        }
        for (final String modifier : MODIFIER_ARRAY) {
            if (modifier.equals(token)) {
                return true;
            }
        }
        return false;
    }

    /**
     * Modifier and annotation order does not matter so they are sorted.
     */
    private void sortModifiers(final List<String> lineTokenList) {
        int end = 0;
        final int size = lineTokenList.size();
        while (end < size && this.isModifier(lineTokenList.get(end))) {
            end++;
        }
        if (end > 1) {
            Collections.sort(lineTokenList.subList(0, end));
        }
    }

    private boolean isIgnoredImport(final String importString) {
        return importString.startsWith("java.lang.") || importString.startsWith("kotlin.");
    }

    private void endLine(final StringBuilder stringBuilder, final List<String> lineTokenList) {
        if (lineTokenList.isEmpty()) {
            return;
        }
        this.sortModifiers(lineTokenList);
        final int size = lineTokenList.size();
        for (int index = 0; index < size; index++) {
            if (index > 0) {
                stringBuilder.append(' ');
            }
            stringBuilder.append(lineTokenList.get(index));
        }
        stringBuilder.append(NEWLINE);
        lineTokenList.clear();
    }

}
